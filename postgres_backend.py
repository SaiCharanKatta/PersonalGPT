import os
from pathlib import Path
from urllib.parse import unquote, urlsplit

try:
    import streamlit as st
    STREAMLIT_SECRETS = st.secrets
except Exception:
    STREAMLIT_SECRETS = {}

USE_POSTGRES = str(
    STREAMLIT_SECRETS.get(
        "PERSONAL_GPT_USE_POSTGRES",
        os.getenv("PERSONAL_GPT_USE_POSTGRES", "")
    )
).strip() == "1"

DATABASE_URL = (
    str(
        STREAMLIT_SECRETS.get(
            "DATABASE_URL",
            os.getenv("DATABASE_URL", "")
        )
    ).strip()
    if USE_POSTGRES
    else ""
)
SCHEMA = "personalgpt_private"


def postgres_schema():
    source = Path(__file__).with_name("schema.sql").read_text()
    return source.replace(
        "CREATE TABLE ",
        "CREATE TABLE IF NOT EXISTS ",
    ).replace(
        "INTEGER PRIMARY KEY AUTOINCREMENT",
        "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
    ).replace("TEXT DEFAULT CURRENT_TIMESTAMP", "TEXT DEFAULT (CURRENT_TIMESTAMP::text)")


def initialize_schema():
    """Ensure the active private schema and all tables exist on every deploy."""
    if not DATABASE_URL:
        return False
    conn = raw_connection(DATABASE_URL)
    try:
        with conn.cursor() as cursor:
            cursor.execute(f'CREATE SCHEMA IF NOT EXISTS "{SCHEMA}"')
            cursor.execute(f'SET search_path TO "{SCHEMA}", pg_catalog')
            cursor.execute(postgres_schema())
            cursor.execute(
                """
                DO $$
                DECLARE item record;
                DECLARE sequence_name text;
                BEGIN
                    FOR item IN
                        SELECT c.table_name
                        FROM information_schema.columns c
                        WHERE c.table_schema = current_schema()
                          AND c.column_name = 'id'
                    LOOP
                        sequence_name := pg_get_serial_sequence(item.table_name, 'id');
                        IF sequence_name IS NOT NULL THEN
                            EXECUTE format(
                                'SELECT setval(%L, GREATEST(COALESCE((SELECT MAX(id) FROM %I), 0), 1), COALESCE((SELECT MAX(id) FROM %I), 0) > 0)',
                                sequence_name, item.table_name, item.table_name
                            );
                        END IF;
                    END LOOP;
                END $$;
                """
            )
        conn.commit()
        return True
    finally:
        conn.close()


def raw_connection(dsn):
    import psycopg
    # Supabase passwords may contain an unescaped '@'. Parse from the final
    # separator and pass credentials as parameters so the host is unambiguous.
    parsed = urlsplit(dsn)
    userinfo, hostpart = parsed.netloc.rsplit("@", 1)
    username, password = userinfo.split(":", 1)
    return psycopg.connect(
        host=parsed.hostname,
        port=parsed.port or 5432,
        dbname=(parsed.path or "/postgres").lstrip("/") or "postgres",
        user=unquote(username),
        password=unquote(password),
        connect_timeout=10,
        sslmode="require",
        prepare_threshold=None,
    )


def indexed_row(cursor):
    names = tuple(column.name for column in cursor.description or ())

    class Row(dict):
        def __getitem__(self, key):
            return super().__getitem__(names[key] if isinstance(key, int) else key)

    return lambda values: Row(zip(names, values))


class PostgresConnection:
    def __init__(self):
        self.connection = raw_connection(DATABASE_URL)
        self.connection.row_factory = indexed_row
        try:
            self.connection.execute(f"SET search_path TO {SCHEMA}, pg_catalog")
            self.connection.commit()
        except Exception:
            self.connection.close()
            raise

    def execute(self, query, params=None):
        return self.connection.execute(query.replace("?", "%s").replace(
            "CURRENT_TIMESTAMP", "CAST(CURRENT_TIMESTAMP AS TEXT)"
        ), params)

    def insert_id(self, query, params):
        return self.execute(query.strip() + " RETURNING id", params).fetchone()[0]

    def __enter__(self):
        return self

    def __exit__(self, *error):
        return self.connection.__exit__(*error)

    def commit(self):
        self.connection.commit()

    def rollback(self):
        self.connection.rollback()

    def close(self):
        self.connection.close()
